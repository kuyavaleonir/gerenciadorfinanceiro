-- Script SQL para ser executado no SQL Editor do Supabase (supabase.com)

-- 1. Criação da tabela de transações
CREATE TABLE IF NOT EXISTS transacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo TEXT NOT NULL CHECK(tipo IN ('receita', 'despesa')),
    valor NUMERIC(12, 2) NOT NULL CHECK(valor > 0),
    descricao TEXT NOT NULL,
    categoria TEXT NOT NULL,
    data DATE NOT NULL DEFAULT CURRENT_DATE,
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Índice para consultas rápidas por data e categoria
CREATE INDEX IF NOT EXISTS idx_transacoes_data ON transacoes(data DESC);
CREATE INDEX IF NOT EXISTS idx_transacoes_tipo ON transacoes(tipo);

