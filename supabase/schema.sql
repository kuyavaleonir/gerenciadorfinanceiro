-- 4. Liberação de leitura e escrita anônima (ou configure RLS se preferir autenticação)
ALTER TABLE transacoes ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Permitir leitura para todos" 
ON transacoes FOR SELECT USING (true);

CREATE POLICY "Permitir inserção para todos" 
ON transacoes FOR INSERT WITH CHECK (true);

CREATE POLICY "Permitir exclusão para todos" 
ON transacoes FOR DELETE USING (true);
